"""Output formatters: JSON summary and GitHub-flavored Markdown report."""

from __future__ import annotations

import json
from typing import Literal

from benchmark_harness.runner import BenchmarkResult
from benchmark_harness.stats import ComparisonResult, Verdict

OutputFormat = Literal["console", "json", "markdown"]

_VERDICT_EMOJI = {
    Verdict.REGRESSION: "🔴",
    Verdict.IMPROVEMENT: "🟢",
    Verdict.NO_CHANGE: "⚪",
}

_METRIC_LABEL = {
    "wall_s": "Wall time",
    "cpu_s": "CPU time",
    "peak_rss_mb": "Peak RSS",
}

_METRIC_UNIT = {
    "wall_s": "s",
    "cpu_s": "s",
    "peak_rss_mb": "MB",
}

# Hidden marker so the GH Actions commenter can find and update the comment.
_COMMENT_MARKER = "<!-- benchmark-harness-report -->"


def _overall_verdict(comparisons: list[ComparisonResult]) -> Verdict:
    verdicts = {r.verdict for r in comparisons}
    if Verdict.REGRESSION in verdicts:
        return Verdict.REGRESSION
    if Verdict.IMPROVEMENT in verdicts:
        return Verdict.IMPROVEMENT
    return Verdict.NO_CHANGE


def to_json(
    comparisons: list[ComparisonResult],
    before: BenchmarkResult,
    after: BenchmarkResult,
) -> str:
    """Return a compact JSON string summarising the comparison."""
    overall = _overall_verdict(comparisons)
    payload = {
        "overall_verdict": overall.value,
        "before_label": before.label,
        "after_label": after.label,
        "before_runs": before.runs,
        "after_runs": after.runs,
        "metrics": [
            {
                "metric": r.metric,
                "label": _METRIC_LABEL.get(r.metric, r.metric),
                "before_mean": r.before_mean,
                "after_mean": r.after_mean,
                "delta_pct": r.delta_pct,
                "p_value": r.p_value,
                "cohens_d": r.cohens_d,
                "ci_95_low": r.ci_low,
                "ci_95_high": r.ci_high,
                "verdict": r.verdict.value,
                "stat_method": r.stat_method,
                "alpha": r.alpha,
                "min_effect": r.min_effect,
            }
            for r in comparisons
        ],
    }
    return json.dumps(payload, indent=2)


def to_markdown(
    comparisons: list[ComparisonResult],
    before: BenchmarkResult,
    after: BenchmarkResult,
) -> str:
    """Return a GitHub-flavored Markdown report suitable for PR comments."""
    overall = _overall_verdict(comparisons)
    emoji = _VERDICT_EMOJI[overall]

    # Pick one comparison (wall_s preferred) for the method footer
    ref = next((r for r in comparisons if r.metric == "wall_s"), comparisons[0])

    lines: list[str] = [
        _COMMENT_MARKER,
        f"## {emoji} Benchmark Report — `{before.label}` → `{after.label}`",
        "",
        f"**Overall verdict: {overall.value}**",
        "",
        "| Metric | Before | After | Δ% | p-value | Cohen's d | Verdict |",
        "|--------|-------:|------:|---:|--------:|----------:|---------|",
    ]

    for r in comparisons:
        unit = _METRIC_UNIT.get(r.metric, "")
        label = _METRIC_LABEL.get(r.metric, r.metric)
        verdict_cell = f"{_VERDICT_EMOJI[r.verdict]} {r.verdict.value}"
        delta_sign = "+" if r.delta_pct >= 0 else ""
        lines.append(
            f"| {label} "
            f"| {r.before_mean:.4f} {unit} "
            f"| {r.after_mean:.4f} {unit} "
            f"| {delta_sign}{r.delta_pct:.2f}% "
            f"| {r.p_value:.4f} "
            f"| {r.cohens_d:+.3f} "
            f"| {verdict_cell} |"
        )

    # 95% CI detail block for the primary metric
    primary = next((r for r in comparisons if r.metric == "wall_s"), None)
    if primary:
        unit = _METRIC_UNIT.get(primary.metric, "")
        lines += [
            "",
            "<details>",
            f"<summary>95% CI on wall-time delta</summary>",
            "",
            f"[{primary.ci_low:+.4f} {unit}, {primary.ci_high:+.4f} {unit}]",
            "",
            "</details>",
        ]

    lines += [
        "",
        "<details>",
        "<summary>Test settings</summary>",
        "",
        f"- Method: `{ref.stat_method}`",
        f"- Significance level (α): `{ref.alpha}`",
        f"- Minimum effect size (|Cohen's d|): `{ref.min_effect}`",
        f"- Before runs: `{before.runs}` (warmup: `{before.warmup}`)",
        f"- After runs: `{after.runs}` (warmup: `{after.warmup}`)",
        "",
        "> A change is flagged only when **both** p < α **and** |Cohen's d| ≥ min effect,",
        "> so noise alone won't trigger a false regression.",
        "",
        "</details>",
        "",
        "_Generated by [benchmark-harness](https://github.com/benchmark-harness)_",
    ]

    return "\n".join(lines)
